def export(report: Report, directory: Path) -> None:
    """Create a private new output directory under an existing trusted parent; never overwrite evidence."""
    absolute = directory.absolute()
    for part in (absolute, *absolute.parents):
        if part.is_symlink() or part.is_junction():
            raise Rejected("output traverses a link")
    try:
        absolute.mkdir(mode=0o700)
        (absolute / "report.json").write_bytes(canonical(report.data()))
        (absolute / "report.html").write_text(render(report), encoding="utf-8", newline="\n")
        with closing(sqlite3.connect(absolute / "evidence.sqlite")) as connection, connection:
            connection.executescript(
                (Path(__file__).parent / "schema.sql").read_text(encoding="utf-8")
            )
            connection.execute(
                "INSERT INTO assessment VALUES(1,?,?,?,?,?,?)",
                (
                    report.host_id,
                    report.platform,
                    report.policy_digest,
                    report.snapshot_digest,
                    report.observed_at,
                    report.as_of,
                ),
            )
            connection.executemany(
                "INSERT INTO finding VALUES(1,?,?,?,?,?,?,?)",
                [
                    (
                        f.control_id,
                        f.status,
                        json.dumps(f.value),
                        json.dumps(f.expected),
                        f.source,
                        f.review,
                        json.dumps({"ticket": f.exception_ticket, **f.exception_detail})
                        if f.exception_detail
                        else None,
                    )
                    for f in report.findings
                ],
            )
    except (OSError, sqlite3.Error) as error:
        raise Rejected(
            "output unavailable or exists; any partial directory is preserved for inspection"
        ) from error
